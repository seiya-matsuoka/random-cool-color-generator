/**
 * HSL 色空間の値。h は色相の角度、s と l は彩度と明度の百分率を表す。
 * アプリの生成色は整数の h: 160〜270、s: 65〜100、l: 25〜70 に限定する。
 * number 型そのものは範囲や整数を保証しないため、型定義と実行時の検証は別に扱う。
 */
export type Hsl = {
  h: number;
  s: number;
  l: number;
};

/** RGB の各成分を 0〜255 の整数で表す。実際の整数化は HSL からの変換時に行う。 */
export type Rgb = {
  r: number;
  g: number;
  b: number;
};

/**
 * 採用された 1 回の生成結果。履歴とお気に入りは、この記録を使って元の色と生成情報を扱う。
 * type はオブジェクトの形を型検査に伝えるもので、記録の生成や保存データの検証は行わない。
 */
export type ColorRecord = {
  /** 記録単位の UUID。同じ HEX の生成記録も区別し、色の同一性の判定には使用しない。 */
  id: string;
  /** シードに用いた Unix epoch からのミリ秒。表示時のタイムゾーンには依存しない。 */
  generatedAt: number;
  /** 呼び出し側が管理するページ内の生成要求の連番。候補の再試行では増やさない。 */
  sequence: number;
  /** 採用された候補の試行番号。初回は 0、最大 8 候補目は 7 となる。 */
  attempt: number;
  /** 採用された候補の SHA-256 全体を表す、小文字 64 桁の 16 進数文字列。 */
  hash: string;
  /** ハッシュから割り当てた元の整数値。RGB への変換で丸めても、この値を保持する。 */
  hsl: Hsl;
  /** 大文字の #RRGGBB。お気に入りでは、この値を同じ色かどうかの基準にする。 */
  hex: string;
};
